bool process_record_user(uint16_t keycode, keyrecord_t* record) {
    switch (keycode) {
        case KC_UPDIR:
            if (record->event.pressed) {
                SEND_STRING("../");
            }

            return false;
        case UD_QUOT:
            if (record->event.pressed) {
                SEND_STRING("' ");
            }

            return false;
        case UD_DQUO:
            if (record->event.pressed) {
                SEND_STRING("\" ");
            }

            return false;
        case UD_CIRC:
            if (record->event.pressed) {
                SEND_STRING("^ ");
            }

            return false;
        case UD_GRV:
            if (record->event.pressed) {
                SEND_STRING("` ");
            }

            return false;
        case UD_TILD:
            if (record->event.pressed) {
                SEND_STRING("~ ");
            }

            return false;
        // case KC_MAGI:
        //     if (record->event.pressed) {
        //         process_magi(get_last_keycode(), get_last_mods());
        //     }
        //     return false;
    }

    return true;
}
